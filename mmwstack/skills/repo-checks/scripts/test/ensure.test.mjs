const engine = fileURLToPath(new URL('../check.mjs', import.meta.url));
const output = result => result.stdout + result.stderr;
function realGit(f, cwd, ...args) {
  const result = spawnSync('git', args, { cwd, env: f.env, encoding: 'utf8', timeout: 15_000 });
  assert.ifError(result.error);
  return result;
}
function snapshot(root) {
  const entries = [];
  function visit(path) {
    const stat = statSync(path);
    entries.push([relative(root, path), stat.mode,
      stat.isDirectory() ? null : readFileSync(path).toString('base64')]);
    if (stat.isDirectory()) for (const name of readdirSync(path).sort()) visit(join(path, name));
  }
  visit(root);
  return entries;
}
function facts(result, status, check = false) {
  assert.equal(result.status, status, output(result));
  assert.equal(result.stderr, '');
  assert.equal(result.stdout.trim().split('\n').length, 1);
  const data = JSON.parse(result.stdout);
  assert.deepEqual(Object.keys(data), ['mode', 'ok', 'exit_code', 'check', 'pending', 'changed', 'retained', 'findings']);
  assert.equal(data.mode, 'ensure');
  assert.equal(data.ok, status === 0);
  assert.equal(data.exit_code, status);
  assert.equal(data.check, check);
  for (const name of ['pending', 'changed', 'retained', 'findings']) assert.ok(Array.isArray(data[name]));
  for (const item of [...data.pending, ...data.changed]) {
    assert.deepEqual(Object.keys(item), ['kind', 'path', 'message']);
    for (const value of Object.values(item)) assert.equal(typeof value, 'string');
  }
  for (const item of data.retained) {
    assert.deepEqual(Object.keys(item), ['path', 'reason']);
    assert.equal(typeof item.path, 'string');
    assert.equal(typeof item.reason, 'string');
  }
  for (const item of data.findings) {
    assert.equal(typeof item.rule, 'string');
    assert.equal(typeof item.message, 'string');
  }
  return data;
}
function installPrek(f, t) {
  f.git('config', '--unset', 'core.hooksPath');
  f.write('.pre-commit-config.yaml', 'repos: []\n');
  const result = spawnSync('prek', ['install', '--hook-type', 'pre-commit', '--hook-type', 'pre-push'], {
    cwd: f.repo, env: f.env, encoding: 'utf8', timeout: 15_000,
  });
  if (result.error?.code === 'ENOENT') {
    t.skip('Install real prek: brew install prek (or uv tool install prek).');
    return false;
  }
  assert.ifError(result.error);
  assert.equal(result.status, 0, output(result));
  for (const name of ['pre-commit', 'pre-push']) {
    assert.match(readFileSync(join(f.repo, '.git/hooks', name), 'utf8'),
      /^#!\/bin\/sh\n# File generated by prek: https:\/\/github.com\/j178\/prek\n/);
  }
  return true;
}

test('a fresh clone is repaired through scripts/check and a second ensure changes nothing', t => {
  const f = fixture(t);
  const clone = join(f.root, 'clone');
  f.git('clone', '--template=', join(f.root, 'origin.git'), clone);
  assert.equal(realGit(f, clone, 'symbolic-ref', '--short', 'HEAD').stdout.trim(), 'main');
  for (const name of ['pre-commit', 'pre-push']) chmodSync(join(clone, '.githooks', name), 0o644);
  const content = ['scripts/check', '.githooks/pre-commit', '.githooks/pre-push']
    .map(path => readFileSync(join(clone, path)));
  const first = facts(f.invoke(['ensure', '--json'], { cwd: clone }), 0);
  assert.deepEqual(first.changed.map(item => item.path), ['core.hooksPath', '.githooks/pre-commit', '.githooks/pre-push']);
  assert.deepEqual(first.pending, []);
  assert.deepEqual(first.findings, []);
  assert.equal(realGit(f, clone, 'config', 'core.hooksPath').stdout.trim(), '.githooks');
  ['scripts/check', '.githooks/pre-commit', '.githooks/pre-push'].forEach((path, index) => {
    assert.deepEqual(readFileSync(join(clone, path)), content[index]);
    assert.equal(statSync(join(clone, path)).mode & 0o111, 0o111);
  });
  const before = snapshot(clone);
  const second = f.invoke(['ensure'], { cwd: clone });
  assert.equal(second.status, 0, output(second));
  assert.equal(output(second), '');
  assert.deepEqual(snapshot(clone), before);
  const healthy = facts(f.invoke(['ensure', '--check', '--json'], { cwd: clone }), 0, true);
  assert.deepEqual(healthy.pending, []);
  assert.deepEqual(healthy.changed, []);
  assert.deepEqual(healthy.retained, []);
  assert.deepEqual(healthy.findings, []);
  assert.equal(output(f.invoke(['ensure', '--check'], { cwd: clone })), '');
  assert.deepEqual(snapshot(clone), before);
});

test('ensure --check lists every pending repair including real prek hooks and writes nothing', t => {
  const f = fixture(t);
  if (!installPrek(f, t)) return;
  for (const name of ['pre-commit', 'pre-push']) chmodSync(join(f.repo, '.githooks', name), 0o644);
  f.write('.scratch/check/log.txt', 'old log\n');
  f.write('.worktrees/orphan/old.txt', 'old checkout\n');
  const before = snapshot(f.repo);
  const pending = facts(f.cli('ensure', '--check', '--json'), 1, true);
  assert.deepEqual(pending.pending.map(item => [item.kind, item.path]), [
    ['hooks-path', 'core.hooksPath'],
    ['hook-executable', '.githooks/pre-commit'],
    ['hook-executable', '.githooks/pre-push'],
    ['prek-hook', '.git/hooks/pre-commit'],
    ['prek-hook', '.git/hooks/pre-push'],
    ['old-folder', '.scratch/check'],
    ['old-folder', '.worktrees/orphan'],
  ]);
  assert.deepEqual(pending.changed, []);
  assert.deepEqual(pending.findings, []);
  const text = f.cli('ensure', '--check');
  assert.equal(text.status, 1, output(text));
  for (const item of pending.pending) assert.ok(text.stdout.includes(`PENDING ${item.path}: ${item.message}`));
  assert.deepEqual(snapshot(f.repo), before);
  const fixed = facts(f.cli('ensure', '--json'), 0);
  assert.deepEqual(fixed.changed, pending.pending);
  assert.deepEqual(fixed.pending, []);
  for (const path of ['.git/hooks/pre-commit', '.git/hooks/pre-push', '.scratch/check', '.worktrees/orphan']) {
    assert.equal(existsSync(join(f.repo, path)), false, path);
  }
  assert.equal(realGit(f, f.repo, 'config', 'core.hooksPath').stdout.trim(), '.githooks');
  assert.deepEqual(facts(f.cli('ensure', '--check', '--json'), 0, true).pending, []);
  assert.equal(output(f.cli('ensure')), '');
});

test('cleanup removes scratch and only the unlisted child without .git, reporting both retained children when healthy', t => {
  const f = fixture(t);
  const listed = join(f.repo, '.worktrees/listed');
  f.git('worktree', 'add', '-b', 'listed', listed);
  f.write('.worktrees/has-git/.git', 'gitdir: elsewhere\n');
  f.write('.worktrees/has-git/keep.txt', 'keep\n');
  f.write('.worktrees/orphan/remove.txt', 'remove\n');
  f.write('.scratch/check/log.txt', 'remove\n');
  const kept = [snapshot(listed), snapshot(join(f.repo, '.worktrees/has-git'))];
  const expected = [
    { path: '.worktrees/has-git', reason: 'has a .git entry' },
    { path: '.worktrees/listed', reason: 'listed by git as a worktree' },
  ];
  const pending = facts(f.cli('ensure', '--check', '--json'), 1, true);
  assert.deepEqual(pending.retained, expected);
  assert.deepEqual(pending.pending.filter(item => item.kind === 'old-folder').map(item => item.path),
    ['.scratch/check', '.worktrees/orphan']);
  assert.deepEqual(facts(f.cli('ensure', '--json'), 0).retained, expected);
  assert.equal(existsSync(join(f.repo, '.scratch/check')), false);
  assert.equal(existsSync(join(f.repo, '.worktrees/orphan')), false);
  assert.deepEqual(snapshot(listed), kept[0]);
  assert.deepEqual(snapshot(join(f.repo, '.worktrees/has-git')), kept[1]);
  const healthy = facts(f.cli('ensure', '--check', '--json'), 0, true);
  assert.deepEqual(healthy.pending, []);
  assert.deepEqual(healthy.retained, expected);
  const text = f.cli('ensure', '--check');
  assert.equal(text.status, 0, output(text));
  for (const item of expected) assert.ok(text.stdout.includes(`RETAIN ${item.path}: ${item.reason}`));
  assert.equal(output(f.cli('ensure')), '', 'Retained children do not make a no-change ensure noisy');
});

test('a linked worktree repairs common default hooks and configuration but cleans only the current checkout', t => {
  const f = fixture(t);
  if (!installPrek(f, t)) return;
  const linked = join(f.root, 'linked');
  f.git('worktree', 'add', '-b', 'linked', linked);
  for (const name of ['pre-commit', 'pre-push']) chmodSync(join(linked, '.githooks', name), 0o644);
  f.write('.scratch/check/main.txt', 'keep in other checkout\n');
  mkdirSync(join(linked, '.scratch/check'), { recursive: true });
  writeFileSync(join(linked, '.scratch/check/linked.txt'), 'remove here\n');
  const before = snapshot(f.root);
  const pending = facts(f.invoke(['ensure', '--check', '--json'], { cwd: linked }), 1, true);
  assert.deepEqual(pending.pending.filter(item => item.kind === 'prek-hook').map(item => item.path),
    ['../repo/.git/hooks/pre-commit', '../repo/.git/hooks/pre-push']);
  assert.deepEqual(snapshot(f.root), before);
  const fixed = facts(f.invoke(['ensure', '--json'], { cwd: linked }), 0);
  assert.deepEqual(fixed.changed, pending.pending);
  assert.equal(realGit(f, linked, 'config', 'core.hooksPath').stdout.trim(), '.githooks');
  assert.equal(realGit(f, f.repo, 'config', 'core.hooksPath').stdout.trim(), '.githooks');
  for (const name of ['pre-commit', 'pre-push']) {
    assert.equal(statSync(join(linked, '.githooks', name)).mode & 0o111, 0o111);
    assert.equal(existsSync(join(f.repo, '.git/hooks', name)), false);
  }
  assert.equal(existsSync(join(linked, '.scratch/check')), false);
  assert.equal(readFileSync(join(f.repo, '.scratch/check/main.txt'), 'utf8'), 'keep in other checkout\n');
  assert.equal(output(f.invoke(['ensure'], { cwd: linked })), '');
  facts(f.invoke(['ensure', '--check', '--json'], { cwd: linked }), 0, true);
});

test('ensure preserves repository-owned hooks, non-prek default hooks and non-directory worktrees entries', t => {
  const f = fixture(t);
  f.write('.githooks/post-checkout', '#!/bin/sh\nprintf repository-owned\n');
  chmodSync(join(f.repo, '.githooks/post-checkout'), 0o644);
  f.write('.git/hooks/custom', '#!/bin/sh\n# This is mine.\n# File generated by prek: https://github.com/j178/prek\n');
  f.write('.git/hooks/pre-commit', '#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\n');
  f.write('.worktrees/notes.txt', 'not a folder\n');
  const paths = ['.githooks/post-checkout', '.git/hooks/custom', '.git/hooks/pre-commit', '.worktrees/notes.txt'];
  const before = paths.map(path => snapshot(join(f.repo, path)));
  const fixed = facts(f.cli('ensure', '--json'), 0);
  assert.deepEqual(fixed.changed.map(item => item.kind), ['hooks-path']);
  assert.deepEqual(fixed.retained, [{ path: '.worktrees/notes.txt', reason: 'not a directory' }]);
  assert.deepEqual(paths.map(path => snapshot(join(f.repo, path))), before);
});

for (const [name, breakConfig, pattern] of [
  ['missing', f => unlinkSync(join(f.repo, '.agents/checks.json')), /checks\.json/],
  ['malformed JSON', f => f.write('.agents/checks.json', '{invalid'), /checks\.json/],
  ['invalid schema', f => f.config({}), /integration: required field/],
  ['invalid integration', f => f.config({ ...cleanConfig(), integration: 'missing' }), /not a remote branch/],
  ['protected command', f => {
    const config = cleanConfig();
    config.lanes.push({ id: 'shop', kind: 'owner-only', command: config.checks[0].run, tests: [], reason: 'Real shop.', run_by: 'owner' });
    f.config(config);
  }, /equals protected owner-only lane/],
]) test(`ensure refuses ${name} Check Config before any mutation`, t => {
  const f = fixture(t);
  f.write('.scratch/check/log.txt', 'must stay\n');
  chmodSync(join(f.repo, '.githooks/pre-commit'), 0o644);
  breakConfig(f);
  const before = snapshot(f.repo);
  for (const check of [false, true]) {
    const data = facts(f.cli('ensure', ...(check ? ['--check'] : []), '--json'), 2, check);
    assert.match(data.findings.map(item => item.message).join('\n'), pattern);
    assert.deepEqual(data.changed, []);
    assert.deepEqual(data.pending, []);
    assert.deepEqual(snapshot(f.repo), before);
  }
  const text = f.cli('ensure');
  assert.equal(text.status, 2, output(text));
  assert.match(text.stdout, pattern);
});

for (const path of ['scripts/check', '.githooks/pre-commit', '.githooks/pre-push']) {
  for (const state of ['absent', 'different']) test(`ensure never installs or overwrites ${path} when ${state}`, t => {
    const f = fixture(t);
    if (state === 'absent') unlinkSync(join(f.repo, path));
    else f.write(path, '#!/bin/sh\n# repository edit\n');
    f.write('.scratch/check/log.txt', 'must stay\n');
    const before = snapshot(f.repo);
    for (const check of [false, true]) {
      const result = spawnSync(process.execPath, [engine, 'ensure', ...(check ? ['--check'] : []), '--json'], {
        cwd: f.repo, env: f.env, encoding: 'utf8', timeout: 15_000,
      });
      assert.ifError(result.error);
      const data = facts(result, 2, check);
      assert.equal(data.findings[0].rule, 'template');
      assert.equal(data.findings[0].path, path);
      assert.match(data.findings[0].message, /differs from canonical/);
      assert.deepEqual(data.changed, []);
      assert.deepEqual(data.pending, []);
      assert.deepEqual(snapshot(f.repo), before);
    }
  });
}

test('ensure accepts only --check and --json and rejects extra arguments without writes', t => {
  const f = fixture(t);
  const before = snapshot(f.repo);
  for (const args of [['--all'], ['--only', 'unit'], ['--base', 'main'], ['--typo'], ['extra'], ['--check', '--check']]) {
    const data = facts(f.cli('ensure', ...args, '--json'), 2, args.includes('--check'));
    assert.equal(data.findings[0].rule, 'usage');
    assert.match(data.findings[0].message, /ensure \[--check\] \[--json\]/);
    assert.deepEqual(data.changed, []);
  }
  assert.deepEqual(snapshot(f.repo), before);
});
